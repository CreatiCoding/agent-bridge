// End-to-end check of the control page (ui/) against a running server and one agent on this machine
// (see README: 개발). A phone drives; the Mac's browser links the agent. Uses a real `claude` session (a few
// tokens). Needs playwright (not a dependency of this repo):
//   PLAYWRIGHT=/path/to/node_modules/playwright/index.mjs AGENT_A=/tmp/agentA WORK=<folder> SHOTS=<folder> node test/e2e-ui.mjs
import fs from 'node:fs'
import path from 'node:path'

const { chromium } = await import(process.env.PLAYWRIGHT)
const SITE = process.env.SITE || 'http://localhost:4399'
const [home, work, shots] = [process.env.AGENT_A, process.env.WORK, process.env.SHOTS]
const MODEL = process.env.MODEL ?? 'claude-haiku-4-5-20251001'
const cfg = JSON.parse(fs.readFileSync(path.join(home, 'agent.json'), 'utf8'))
const step = (s) => console.log(`\n== ${s}`)
const ok = (cond, what) => {
  console.log(`${cond ? 'PASS' : 'FAIL'} ${what}`)
  if (!cond) process.exitCode = 1
}

const browser = await chromium.launch(process.env.CHANNEL ? { channel: process.env.CHANNEL } : {})
const newCtx = async (viewport) => {
  const c = await browser.newContext({ viewport })
  await c.request.get(`${SITE}/api/auth/dev?login=tester`)
  return c
}
const mac = await newCtx({ width: 1280, height: 820 })
const phone = await newCtx({ width: 390, height: 844 })
const errors = []
const watch = (page, name) => {
  page.on('pageerror', (e) => errors.push(`${name}: ${e.message}`))
  page.on('console', (m) => m.type() === 'error' && !/Failed to load resource/.test(m.text()) && errors.push(`${name}: ${m.text()}`))
  return page
}

step('연동')
const bridge = await mac.newPage()
await bridge.goto(`${SITE}/bridge#port=${cfg.port}&key=${cfg.key}`)
await bridge.waitForFunction(() => document.getElementById('server-text')?.textContent === '연결됨', null, { timeout: 15000 })
const app = watch(await phone.newPage(), 'phone')
const shot = (name, page = app) => page.screenshot({ path: `${shots}/${name}.png` })
await app.goto(SITE)
await app.waitForSelector('.list', { timeout: 15000 })
await app.waitForFunction(() => !document.querySelector('.list-summary .sum-off'), null, { timeout: 15000 })
// A phone's list says only what needs attention above it (the count is a PC's).
ok(!/세션 \d+개/.test((await app.locator('.list-summary').textContent({ timeout: 1000 }).catch(() => '')) ?? ''), '폰 목록 위에 세션 수가 없고, 맥은 연결됨')
await shot('ui-0-list')

step('새 세션')
await app.click('.fab')
await app.waitForSelector('.folder-item', { timeout: 15000 })
await app.fill('input.input.mono', work)
await app.press('input.input.mono', 'Enter')
await app.waitForFunction(() => !document.querySelector('.folder-item .spinner'), null, { timeout: 15000 })
await app.fill('textarea.input', 'Reply with exactly the word BRIDGE_ONE and nothing else. Do not use any tools.')
if (MODEL) {
  await app.getByRole('button', { name: /모델 · effort/ }).click()
  await app.locator('select.input').first().selectOption(MODEL)
}
await shot('ui-1-new')
await app.getByRole('button', { name: '시작' }).click()
await app.waitForURL(/\/s\/[\w-]+$/, { timeout: 60000 })
const sid = app.url().split('/').pop()
const answered = (re, timeout = 120000) => app.waitForFunction((src) => [...document.querySelectorAll('.msg-text')].some((m) => new RegExp(src).test(m.textContent)), re, { timeout })
await answered('BRIDGE_ONE')
ok(true, '첫 답이 화면에 도착')
ok((await app.locator('.dcard.open').count()) === 0, '폴더 신뢰 창을 사람에게 묻지 않음')
await shot('ui-2-answer')

step('이어서 보내기: 흐린 말풍선 → 실제 줄')
await app.fill('.inputbox textarea', 'Reply with exactly the word BRIDGE_TWO and nothing else.')
await app.click('.inputbox .send')
ok(await app.locator('.bubble.sending').count().then((n) => n >= 1), '보낸 글이 바로 흐리게 보임')
await answered('BRIDGE_TWO')
await app.waitForFunction(() => !document.querySelector('.bubble.sending'), null, { timeout: 15000 })
ok(true, '흐린 말풍선이 실제 줄로 바뀜')

step('클립보드 그림 붙이기')
await phone.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: SITE })
await app.evaluate(async () => {
  const c = Object.assign(document.createElement('canvas'), { width: 8, height: 8 })
  c.getContext('2d').fillRect(0, 0, 8, 8)
  const blob = await new Promise((r) => c.toBlob(r, 'image/png'))
  await navigator.clipboard.write([new ClipboardItem({ 'image/png': blob })])
})
await app.getByRole('button', { name: '사진 첨부' }).click()
await app.getByText('클립보드에서 붙여넣기').click()
await app.waitForSelector('.attach-row .attach img', { timeout: 5000 })
ok((await app.locator('.attach-row .attach').count()) === 1, '사진 버튼 → 클립보드에서 붙여넣기로 그림이 붙음')
await app.locator('.attach-row .attach button').click()
ok((await app.locator('.attach-row').count()) === 0, '붙인 그림을 뺄 수 있음')

step('HTML 블록은 그려서 보인다')
await app.fill('.inputbox textarea', 'Reply with only a fenced code block with the language html whose content is exactly: <p><b>HTML_OK</b></p>')
await app.click('.inputbox .send')
await app.waitForSelector('.html-prev iframe', { timeout: 120000 })
const drawn = await app.waitForFunction(() => [...document.querySelectorAll('.html-prev iframe')].some((f) => f.contentDocument?.body?.textContent?.includes('HTML_OK')), null, { timeout: 15000 }).then(() => true, () => false)
ok(drawn, 'HTML 블록이 프레임 안에 그려짐')

step('권한 카드')
await app.fill('.inputbox textarea', 'Run this exact shell command with the Bash tool: echo bridge > e2e-ui.txt . Then reply DONE_THREE.')
await app.click('.inputbox .send')
await app.waitForSelector('.dcard.open', { timeout: 120000 })
await shot('ui-3-permission')
ok((await app.locator('.dcard.open .dcard-detail pre').textContent())?.includes('echo bridge'), '카드에 실행할 명령이 보임')
await app.locator('.dcard.open .opt.primary').click()
await answered('DONE_THREE')
ok(fs.existsSync(path.join(work, 'e2e-ui.txt')), '허용한 명령이 실행됨')
await app.waitForSelector('.dcard.closed', { timeout: 15000 })
ok(true, '카드가 답한 상태로 접힘')

step('메뉴 · 이름 · 설정 · 화면')
await app.getByRole('button', { name: '세션 메뉴' }).click()
await app.getByRole('menuitem', { name: /이름 바꾸기/ }).click()
await app.fill('.sheet input.input', 'e2e 세션')
await app.getByRole('button', { name: '바꾸기' }).click()
await app.waitForFunction(() => document.querySelector('.topbar-title b')?.textContent === 'e2e 세션', null, { timeout: 15000 })
ok(true, '이름을 바꿈')
await app.locator('.chips .chip').first().click()
await app.waitForSelector('.sheet select.input', { timeout: 10000 })
await shot('ui-4-settings')
await app.keyboard.press('Escape')
// 터미널 화면 is in the ⋯ menu on a phone and a PC alike (a PC header has 새로고침 in its place).
await app.getByRole('button', { name: '세션 메뉴' }).click()
await app.getByRole('menuitem', { name: /터미널 화면/ }).click()
await app.waitForFunction(() => (document.querySelector('.screen-pre')?.textContent ?? '').length > 20, null, { timeout: 20000 })
await shot('ui-5-screen')
ok(true, '터미널 화면을 읽음')
await app.keyboard.press('Escape')

step('PC 화면')
const pc = watch(await mac.newPage(), 'pc')
await pc.goto(`${SITE}/s/${sid}`)
await pc.waitForFunction(() => document.querySelectorAll('.msg-text').length >= 3, null, { timeout: 15000 })
await shot('ui-6-pc', pc)
ok(await pc.locator('.side .srow.active').count().then((n) => n === 1), 'PC 목록에서 지금 세션이 표시됨')
ok((await pc.locator('.topbar').getByRole('button', { name: '새로고침' }).count()) === 1 && (await pc.locator('.topbar').getByRole('button', { name: '터미널 화면' }).count()) === 0, 'PC 머리줄에 새로고침 버튼, 터미널 화면은 메뉴에')
await pc.getByRole('button', { name: '세션 메뉴' }).click()
ok((await pc.getByRole('menuitem', { name: /터미널 화면/ }).count()) === 1 && (await pc.getByRole('menuitem', { name: /^새로고침/ }).count()) === 0, 'PC ⋯ 메뉴에 터미널 화면이 있고 새로고침은 없음')
await pc.keyboard.press('Escape')

step('휴면: 목록에서 숨김 · 깨워서 열기')
await pc.request.post(`${SITE}/api/sessions/${sid}/settings`, { headers: { 'content-type': 'application/json', origin: SITE }, data: { resting: true } })
await pc.goto(`${SITE}/stats`)
await pc.waitForSelector('.side .list', { timeout: 15000 })
await pc.waitForFunction(() => !document.querySelector('.side .srow'), null, { timeout: 10000 }).then(() => ok(true, '휴면 세션은 그룹 보기에서 숨음'), () => ok(false, '휴면 세션은 그룹 보기에서 숨음'))
await pc.getByRole('button', { name: /휴면 세션 하나 꺼내 쓰기 · 1개 남음/ }).first().click()
await pc.waitForURL(new RegExp(`/s/${sid}$`), { timeout: 10000 })
await pc.waitForSelector('.side .srow.active:not(.resting)', { timeout: 10000 }).then(() => ok(true, '꺼내 쓰기 버튼 한 번에 휴면이 풀리고 그 세션이 열림'), () => ok(false, '꺼내 쓰기 버튼 한 번에 휴면이 풀리고 그 세션이 열림'))
await pc.request.post(`${SITE}/api/sessions/${sid}/settings`, { headers: { 'content-type': 'application/json', origin: SITE }, data: { resting: true } })
await pc.goto(`${SITE}/stats`)
await pc.waitForFunction(() => !document.querySelector('.side .srow'), null, { timeout: 10000 })
await pc.goto(`${SITE}/s/${sid}`)
await pc.waitForSelector('.side .srow.active:not(.resting)', { timeout: 10000 }).then(() => ok(true, '휴면 세션을 주소로 바로 열어도 휴면이 풀림'), () => ok(false, '휴면 세션을 주소로 바로 열어도 휴면이 풀림'))
await pc.getByRole('button', { name: '세션 메뉴' }).click()
await pc.locator('.menu-label', { hasText: /^휴면$/ }).click()
await pc.waitForURL((u) => u.pathname === '/', { timeout: 10000 }).then(() => ok(true, '세션 화면에서 휴면 → 목록 화면으로'), () => ok(false, '세션 화면에서 휴면 → 목록 화면으로'))
await pc.waitForTimeout(1500)
ok((await pc.locator('.list .srow').count()) === 0, '휴면으로 둔 세션은 숨고, 다시 깨지 않음')
await pc.request.post(`${SITE}/api/sessions/${sid}/settings`, { headers: { 'content-type': 'application/json', origin: SITE }, data: { resting: false } })

step('통계 · 기기')
await app.goto(`${SITE}/stats`)
await app.waitForSelector('.tile', { timeout: 20000 })
await shot('ui-7-stats')
await app.goto(`${SITE}/hosts/${cfg.hostId}`)
await app.waitForSelector('.logline', { timeout: 20000 })
await shot('ui-8-host')
ok(true, '통계와 기기 화면이 열림')

step('옛 주소(/#/) · 화면 안 링크')
await app.goto(`${SITE}/#/s/${sid}`)
await app.waitForURL((u) => u.pathname === `/s/${sid}` && !u.hash, { timeout: 10000 })
await app.waitForFunction(() => document.querySelectorAll('.msg-text').length >= 3, null, { timeout: 15000 })
ok(true, '옛 주소 /#/s/<id> 가 /s/<id> 로 바뀌고 그 세션이 열림')
await app.goto(`${SITE}/#/new?group=nope`)
await app.waitForURL((u) => u.pathname === '/new' && u.search === '?group=nope', { timeout: 10000 })
ok(true, '옛 주소의 물음표 뒤도 그대로 옮김')
await app.goto(`${SITE}/`)
await app.evaluate(() => ((window).__noReload = 1))
await app.locator(`a.srow[href="/s/${sid}"]`).first().click()
await app.waitForURL((u) => u.pathname === `/s/${sid}`, { timeout: 10000 })
ok(await app.evaluate(() => (window).__noReload === 1), '화면 안 링크는 페이지를 새로 불러오지 않고 옮김')
await app.goBack()
await app.waitForURL((u) => u.pathname === '/', { timeout: 10000 })
ok(await app.evaluate(() => (window).__noReload === 1), '뒤로 가기도 새로 불러오지 않고 목록으로')
const anon = await browser.newContext()
const r = await anon.request.get(`${SITE}/s/${sid}`, { maxRedirects: 0 })
ok(r.status() === 302 && /^\/(api\/auth\/github\?next=%2Fs%2F|$)/.test(r.headers().location ?? ''), `로그인 전 /s/<id> 는 로그인으로 보냄(${r.status()} ${r.headers().location})`)
await anon.close()

step('종료 · 이어서 열기')
await app.goto(`${SITE}/s/${sid}`)
await app.getByRole('button', { name: '세션 메뉴' }).click()
await app.getByRole('menuitem', { name: /^종료/ }).click()
await app.getByRole('button', { name: '끝내기' }).click()
await app.waitForSelector('text=끝난 세션이에요', { timeout: 30000 })
ok(true, '끝난 세션 안내가 보임')
await app.getByRole('button', { name: '이어서 열기' }).click()
await app.waitForFunction(() => !document.body.textContent.includes('끝난 세션이에요'), null, { timeout: 120000 })
await app.fill('.inputbox textarea', 'Reply with exactly the word BRIDGE_FOUR and nothing else.')
await app.click('.inputbox .send')
await answered('BRIDGE_FOUR')
ok(true, '이어서 연 세션이 같은 대화로 답함')
await shot('ui-9-resumed')

step('정리')
await app.getByRole('button', { name: '세션 메뉴' }).click()
await app.getByRole('menuitem', { name: /^종료/ }).click()
await app.getByRole('button', { name: '끝내기' }).click()
ok(!errors.length, `페이지 오류 없음${errors.length ? `: ${errors.join(' | ')}` : ''}`)
await browser.close()
